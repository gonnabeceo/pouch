type Replace = (m: RegExpExecArray, tr: (s: string) => string) => string

// Сообщения сервера с подставленными значениями: шаблон → перевод.
export const SERVER_PATTERNS: [RegExp, Replace][] = [
  [/^Суб-аккаунт (.+)$/, (m) => `Sub-account ${m[1]}`],
  [/^Адрес (\S+): (.+)$/, (m, tr) => `${m[1]} address: ${tr(m[2])}`],
  [/^Недопустимый символ «(.+)»$/, (m) => `invalid character “${m[1]}”`],
  [/^Неизвестная сеть: (.+)$/, (m) => `unknown network: ${m[1]}`],
  [/^Пароль короче (\d+) символов$/, (m) => `Password is shorter than ${m[1]} characters`],
  [/^Новый пароль короче (\d+) символов$/, (m) => `New password is shorter than ${m[1]} characters`],
  [/^Слишком много попыток, подождите (\d+) с$/, (m) => `Too many attempts, wait ${m[1]} s`],
  [/^(.+): нет ответа \((.+)\)$/, (m) => `${m[1]}: no response (${m[2]})`],
  [/^(.+): ответ не JSON$/, (m) => `${m[1]}: response is not JSON`],
  [/^ошибка обработки ответа \((.+)\)$/, (m) => `failed to process the response (${m[1]})`],
  [/^Solana RPC: (\S+) — ошибка (.+)$/, (m) => `Solana RPC: ${m[1]} — error ${m[2]}`],
  [/^DeFi не обновился \((.+)\), показан кэш$/, (m, tr) => `DeFi didn't update (${tr(m[1])}), showing cached data`],
  [/^(.+): сумма расходится с интерфейсом Hyperliquid на (.+)$/, (m, tr) => `${tr(m[1])}: total differs from the Hyperliquid UI by ${m[2]}`],
  [/^(.+); (.+)$/, (m, tr) => `${tr(m[1])}; ${tr(m[2])}`],
]
